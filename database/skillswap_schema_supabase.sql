BEGIN;

-- =========================================
-- UNIVERSIDADES / CAMPUS / AULAS
-- =========================================
CREATE TABLE IF NOT EXISTS universidades (
    id_universidad      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_universidad  VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS campus (
    id_campus       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_campus   VARCHAR(100),
    id_universidad  INT REFERENCES universidades(id_universidad)
);

CREATE TABLE IF NOT EXISTS aulas (
    id_aula      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_aula  VARCHAR(100),
    id_campus    INT REFERENCES campus(id_campus)
);

-- =========================================
-- FACULTADES / CARRERAS
-- =========================================
CREATE TABLE IF NOT EXISTS facultades (
    id_facultad      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_facultad  VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS carreras (
    id_carrera      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_carrera  VARCHAR(100),
    id_facultad     INT REFERENCES facultades(id_facultad)
);

-- =========================================
-- ROLES / USUARIOS
-- =========================================
CREATE TABLE IF NOT EXISTS roles (
    id_rol      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol  VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100),
    apellido        VARCHAR(100),
    email           VARCHAR(150) UNIQUE,
    password_hash   VARCHAR(255),
    carrera         VARCHAR(100),
    semestre        INT,
    fecha_registro  TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS usuario_rol (
    id_usuario  INT REFERENCES usuarios(id_usuario),
    id_rol      INT REFERENCES roles(id_rol),
    PRIMARY KEY (id_usuario, id_rol)
);

-- Subtipos de usuario: la PK es a la vez FK a usuarios
CREATE TABLE IF NOT EXISTS estudiantes (
    id_estudiante  INT PRIMARY KEY REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS tutores (
    id_tutor             INT PRIMARY KEY REFERENCES usuarios(id_usuario),
    reputacion_promedio  NUMERIC(2,1),
    total_tutorias       INT DEFAULT 0
);

-- =========================================
-- MATERIAS
-- =========================================
CREATE TABLE IF NOT EXISTS materias (
    id_materia      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_materia  VARCHAR(100),
    codigo_materia  VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS usuario_materia (
    id_usuario  INT REFERENCES usuarios(id_usuario),
    id_materia  INT REFERENCES materias(id_materia),
    nivel       VARCHAR(50),
    PRIMARY KEY (id_usuario, id_materia)
);

-- =========================================
-- DISPONIBILIDAD TUTOR
-- =========================================
CREATE TABLE IF NOT EXISTS disponibilidad_tutor (
    id_disponibilidad  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tutor           INT REFERENCES tutores(id_tutor),
    dia_semana         VARCHAR(20),
    hora_inicio        TIME,
    hora_fin           TIME
);

-- =========================================
-- SOLICITUDES / MATCHING / SESIONES
-- =========================================
CREATE TABLE IF NOT EXISTS solicitudes_tutoria (
    id_solicitud     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante    INT REFERENCES estudiantes(id_estudiante),
    id_materia       INT REFERENCES materias(id_materia),
    descripcion      TEXT,
    fecha_solicitud  TIMESTAMPTZ DEFAULT now(),
    estado           VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS matching_tutor (
    id_matching    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud   INT REFERENCES solicitudes_tutoria(id_solicitud),
    id_tutor       INT REFERENCES tutores(id_tutor),
    puntaje_match  NUMERIC(3,2)
);

CREATE TABLE IF NOT EXISTS sesiones_tutoria (
    id_sesion     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud  INT REFERENCES solicitudes_tutoria(id_solicitud),
    id_tutor      INT REFERENCES tutores(id_tutor),
    fecha_inicio  TIMESTAMPTZ,
    fecha_fin     TIMESTAMPTZ,
    modalidad     VARCHAR(50),
    estado        VARCHAR(50)
);

-- =========================================
-- DEPENDIENTES DE LA SESIÓN
-- =========================================
CREATE TABLE IF NOT EXISTS historial_tutorias (
    id_historial    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion       INT REFERENCES sesiones_tutoria(id_sesion),
    fecha_registro  TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS calificaciones (
    id_calificacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion        INT REFERENCES sesiones_tutoria(id_sesion),
    puntuacion       INT,
    comentario       TEXT
);

CREATE TABLE IF NOT EXISTS archivos_compartidos (
    id_archivo      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion       INT REFERENCES sesiones_tutoria(id_sesion),
    nombre_archivo  VARCHAR(255),
    url_archivo     TEXT
);

-- =========================================
-- PROGRESO ESTUDIANTE
-- =========================================
CREATE TABLE IF NOT EXISTS progreso_estudiante (
    id_progreso           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante         INT REFERENCES estudiantes(id_estudiante),
    id_materia            INT REFERENCES materias(id_materia),
    sesiones_completadas  INT DEFAULT 0
);

-- =========================================
-- COMUNICACIÓN
-- =========================================
CREATE TABLE IF NOT EXISTS notificaciones (
    id_notificacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       INT REFERENCES usuarios(id_usuario),
    mensaje          TEXT,
    fecha_envio      TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS mensajes (
    id_mensaje       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_remitente     INT REFERENCES usuarios(id_usuario),
    id_destinatario  INT REFERENCES usuarios(id_usuario),
    contenido        TEXT,
    fecha_envio      TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reportes (
    id_reporte  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario  INT REFERENCES usuarios(id_usuario),
    motivo      TEXT,
    fecha       TIMESTAMPTZ DEFAULT now()
);

-- =========================================
-- SISTEMA
-- =========================================
CREATE TABLE IF NOT EXISTS log_sistema (
    id_log  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    accion  VARCHAR(255),
    fecha   TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS configuraciones (
    id_config  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave      VARCHAR(100),
    valor      VARCHAR(255)
);

-- =========================================
-- ÍNDICES EN CLAVES FORÁNEAS
-- (PostgreSQL no los crea automáticamente, a diferencia de MySQL)
-- =========================================
CREATE INDEX IF NOT EXISTS idx_campus_universidad         ON campus(id_universidad);
CREATE INDEX IF NOT EXISTS idx_aulas_campus               ON aulas(id_campus);
CREATE INDEX IF NOT EXISTS idx_carreras_facultad          ON carreras(id_facultad);
CREATE INDEX IF NOT EXISTS idx_usuario_rol_rol            ON usuario_rol(id_rol);
CREATE INDEX IF NOT EXISTS idx_usuario_materia_materia    ON usuario_materia(id_materia);
CREATE INDEX IF NOT EXISTS idx_disponibilidad_tutor       ON disponibilidad_tutor(id_tutor);
CREATE INDEX IF NOT EXISTS idx_solicitudes_estudiante     ON solicitudes_tutoria(id_estudiante);
CREATE INDEX IF NOT EXISTS idx_solicitudes_materia        ON solicitudes_tutoria(id_materia);
CREATE INDEX IF NOT EXISTS idx_matching_solicitud         ON matching_tutor(id_solicitud);
CREATE INDEX IF NOT EXISTS idx_matching_tutor             ON matching_tutor(id_tutor);
CREATE INDEX IF NOT EXISTS idx_sesiones_solicitud         ON sesiones_tutoria(id_solicitud);
CREATE INDEX IF NOT EXISTS idx_sesiones_tutor             ON sesiones_tutoria(id_tutor);
CREATE INDEX IF NOT EXISTS idx_historial_sesion           ON historial_tutorias(id_sesion);
CREATE INDEX IF NOT EXISTS idx_calificaciones_sesion      ON calificaciones(id_sesion);
CREATE INDEX IF NOT EXISTS idx_archivos_sesion            ON archivos_compartidos(id_sesion);
CREATE INDEX IF NOT EXISTS idx_progreso_estudiante        ON progreso_estudiante(id_estudiante);
CREATE INDEX IF NOT EXISTS idx_progreso_materia           ON progreso_estudiante(id_materia);
CREATE INDEX IF NOT EXISTS idx_notificaciones_usuario     ON notificaciones(id_usuario);
CREATE INDEX IF NOT EXISTS idx_mensajes_remitente         ON mensajes(id_remitente);
CREATE INDEX IF NOT EXISTS idx_mensajes_destinatario      ON mensajes(id_destinatario);
CREATE INDEX IF NOT EXISTS idx_reportes_usuario           ON reportes(id_usuario);

-- =========================================
-- ROW LEVEL SECURITY
-- Supabase expone el esquema public por su API REST con la "anon key".
-- Sin RLS, cualquiera con esa clave podría leer tablas como usuarios
-- (incluido password_hash). Activar RLS sin políticas bloquea ese acceso;
-- el backend Express se conecta como "postgres" (dueño de las tablas),
-- por lo que NO se ve afectado.
-- =========================================
ALTER TABLE universidades         ENABLE ROW LEVEL SECURITY;
ALTER TABLE campus                ENABLE ROW LEVEL SECURITY;
ALTER TABLE aulas                 ENABLE ROW LEVEL SECURITY;
ALTER TABLE facultades            ENABLE ROW LEVEL SECURITY;
ALTER TABLE carreras              ENABLE ROW LEVEL SECURITY;
ALTER TABLE roles                 ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuarios              ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuario_rol           ENABLE ROW LEVEL SECURITY;
ALTER TABLE estudiantes           ENABLE ROW LEVEL SECURITY;
ALTER TABLE tutores               ENABLE ROW LEVEL SECURITY;
ALTER TABLE materias              ENABLE ROW LEVEL SECURITY;
ALTER TABLE usuario_materia       ENABLE ROW LEVEL SECURITY;
ALTER TABLE disponibilidad_tutor  ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitudes_tutoria   ENABLE ROW LEVEL SECURITY;
ALTER TABLE matching_tutor        ENABLE ROW LEVEL SECURITY;
ALTER TABLE sesiones_tutoria      ENABLE ROW LEVEL SECURITY;
ALTER TABLE historial_tutorias    ENABLE ROW LEVEL SECURITY;
ALTER TABLE calificaciones        ENABLE ROW LEVEL SECURITY;
ALTER TABLE archivos_compartidos  ENABLE ROW LEVEL SECURITY;
ALTER TABLE progreso_estudiante   ENABLE ROW LEVEL SECURITY;
ALTER TABLE notificaciones        ENABLE ROW LEVEL SECURITY;
ALTER TABLE mensajes              ENABLE ROW LEVEL SECURITY;
ALTER TABLE reportes              ENABLE ROW LEVEL SECURITY;
ALTER TABLE log_sistema           ENABLE ROW LEVEL SECURITY;
ALTER TABLE configuraciones       ENABLE ROW LEVEL SECURITY;

-- =========================================
-- AUTENTICACIÓN
-- =========================================
-- Email único sin distinguir mayúsculas/minúsculas (el backend además lo guarda en minúsculas)
CREATE UNIQUE INDEX IF NOT EXISTS uq_usuarios_email_lower ON usuarios (lower(email));

-- Nombre de rol único, necesario para el ON CONFLICT de abajo
CREATE UNIQUE INDEX IF NOT EXISTS uq_roles_nombre ON roles (nombre_rol);

-- Roles base del sistema
INSERT INTO roles (nombre_rol) VALUES
    ('estudiante'),
    ('tutor'),
    ('administrador')
ON CONFLICT (nombre_rol) DO NOTHING;

